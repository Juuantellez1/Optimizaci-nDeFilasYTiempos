# BLOQUE 8: SIMULACIÓN DEL RESTAURANTE
# Esta función simula el sistema de colas del restaurante.
# Genera llegadas aleatorias, tiempos de servicio aleatorios
# y calcula el desempeño para cada número de servidores.

def simular_restaurante(nombre_sesion, lambd, mu, servidores, tiempo_sim, reps=30, limite_satisfaccion=5):  # Simula cola
    resultados = []  # Lista de resultados

    for rep in range(reps):  # Repite simulación
        env = simpy.Environment()  # Crea ambiente
        recurso = simpy.Resource(env, capacity=servidores)  # Crea servidores

        esperas = []  # Guarda esperas
        tiempos_sistema = []  # Guarda tiempos totales
        atendidos = 0  # Cuenta atendidos
        llegadas = 0  # Cuenta llegadas

        def cliente():  # Define cliente
            nonlocal atendidos, llegadas  # Usa variables externas
            llegada = env.now  # Guarda llegada
            llegadas += 1  # Suma llegada

            with recurso.request() as req:  # Pide servidor
                yield req  # Espera turno

                espera = env.now - llegada  # Calcula espera
                esperas.append(espera)  # Guarda espera

                servicio = np.random.exponential(1 / mu)  # Genera servicio
                yield env.timeout(servicio)  # Atiende cliente

                tiempo_total = env.now - llegada  # Calcula tiempo total
                tiempos_sistema.append(tiempo_total)  # Guarda tiempo
                atendidos += 1  # Suma atendido

        def generador():  # Genera clientes
            while True:  # Ciclo infinito
                interllegada = np.random.exponential(1 / lambd)  # Tiempo entre llegadas
                yield env.timeout(interllegada)  # Espera llegada
                env.process(cliente())  # Lanza cliente

        env.process(generador())  # Inicia generador
        env.run(until=tiempo_sim)  # Corre simulación

        esperas = np.array(esperas)  # Convierte esperas
        tiempos_sistema = np.array(tiempos_sistema)  # Convierte tiempos

        espera_prom = esperas.mean() if len(esperas) > 0 else 0  # Promedio espera
        tiempo_sistema_prom = tiempos_sistema.mean() if len(tiempos_sistema) > 0 else 0  # Promedio sistema
        satisfaccion = np.mean(esperas <= limite_satisfaccion) if len(esperas) > 0 else 0  # Satisfacción
        utilizacion = lambd / (servidores * mu)  # Utilización

        resultados.append({  # Guarda fila
            "Sesión": nombre_sesion,
            "Servidores": servidores,
            "Espera promedio": espera_prom,
            "Tiempo sistema promedio": tiempo_sistema_prom,
            "Satisfacción <= 5 min": satisfaccion,
            "Atendidos": atendidos,
            "Llegadas simuladas": llegadas,
            "Utilización": utilizacion
        })

    return pd.DataFrame(resultados)  # Retorna tabla


