def resumen_sesion(df, nombre):  # Resume una sesión
    duracion = df["Minuto"].max() - df["Minuto"].min()  # Calcula duración
    entradas = df["# personas que entran"].sum()  # Suma entradas
    salidas = df["# personas que salen"].sum()  # Suma salidas
