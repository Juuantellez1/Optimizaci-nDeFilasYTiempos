# EXPLICACIÓN GENERAL:
# Aquí se calculan los parámetros principales del modelo M/M/s:
# λ: tasa de llegada de clientes.
# μ: cuántas personas puede atender un solo servidor en un minuto.
# s: número de servidores o puntos de atención.

def parametros_modelo(df):  # Calcula λ y μ
    duracion = df["Minuto"].max() - df["Minuto"].min()  # Duración
    entradas = df["# personas que entran"].sum()  # Entradas
    salidas = df["# personas que salen"].sum()  # Salidas
    servidores_base = 2  # servidores base
    lambd = entradas / duracion  # Calcula λ
    mu = (salidas / duracion) / servidores_base  # Calcula μ
    return lambd, mu, duracion, entradas, salidas  # Retorna valores

